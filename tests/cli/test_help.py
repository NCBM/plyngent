"""What a person reads when they ask a command to describe itself: fourteen texts, and two rules about them.

``--help`` is generated by click from the same options the parser is built from, so no wording here is
written twice — but generated text is still text a person reads, and the two rules below are the ones
nothing else in the tree can state: a summary names the act, not this program's insides, and a
help line says what a command does. The texts are kept whole, because a
change nobody meant is the change a snapshot catches and a sentence-by-sentence assertion does not.
``offer`` is the one command with no text here: its one argument is a tuple of objects, which no line can
carry, so the client withholds it, and lists no word that cannot work.
"""

