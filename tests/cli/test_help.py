def _catalog() -> Catalog:
    """The vocabulary this client derives from the kernel's own manifest."""
    return build(KernelManifest(commands=command_specs()), session="main")


def _helps() -> dict[str, str]:
    """Every command's own help, read the way ``/word --help`` reads it."""
    catalog = _catalog()
    return {tag: word_help(catalog, tag) for tag in catalog.offers}


def _option_helps() -> dict[str, str]:
    """The help of every option this client can spell, told apart by the word a person types."""
    catalog = _catalog()
    return {
        f"{tag} {option.opts[0]}": option.help or ""
        for tag, entry in catalog.offers.items()
        for option in entry.command.get_params(click.Context(entry.command))
        if isinstance(option, click.Option)
    }


def test_every_command_still_describes_itself_the_same_way() -> None:
    written = _helps()

    assert set(written) == set(EXPECTED), "a word that appeared or went away is a change as well"
    changed = {tag: text for tag, text in written.items() if EXPECTED[tag] != text}
    assert not changed, "\n=== ".join(f"{tag}:{text}" for tag, text in changed.items())


def test_the_only_word_this_client_withholds_is_the_one_no_line_can_carry() -> None:
    catalog = _catalog()

    assert set(catalog.withheld) == {"offer"}, "a tuple of objects is the one argument a line has no spelling for"


def test_a_summary_names_the_act_and_not_this_programs_insides() -> None:
    """A person reads a summary to find a word to type, and an internal name is one they cannot type."""
    said = {spec.name: spec.summary for spec in command_specs()} | _option_helps()
    wrong = {where: [word for word in INTERNAL if word in text] for where, text in said.items()}

    assert [where for where, words in wrong.items() if words] == [], "a word from inside is not help"


def test_help_says_what_a_command_does_and_not_what_it_avoids() -> None:
    """A contrast belongs in the design note; the line a person reads is about what will happen."""
    wrong = {tag: [word for word in DENIALS if word in text] for tag, text in _helps().items()}

    assert [tag for tag, words in wrong.items() if words] == [], "a denial clause is not help"
